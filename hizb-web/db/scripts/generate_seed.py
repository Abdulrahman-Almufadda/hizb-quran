"""Generate the seed SQL files in db/init/ from the SQLite DB of the original mobile app.

Usage: python3 db/scripts/generate_seed.py path/to/quran.db
(the SQLite file is assets/data/quran.db in the original hizb-quran mobile app)

Output is split into several files (02-seed-surahs.sql, 03-seed-ayahs-NN.sql) because
Postgres runs /docker-entrypoint-initdb.d/*.sql in alphabetical order and smaller files
are easier to review and upload.
"""
import sqlite3
import sys
from pathlib import Path

ROWS_PER_FILE = 800

init_dir = Path(__file__).parent.parent / "init"
src = sqlite3.connect(sys.argv[1])
HEADER = "-- GENERATED by db/scripts/generate_seed.py - do not edit by hand.\n"


def esc(v):
    if v is None:
        return r"\N"
    return str(v).replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n").replace("\r", "\\r")


def copy_block(table, columns, rows):
    lines = [f"COPY {table} ({', '.join(columns)}) FROM stdin;\n"]
    lines += ["\t".join(esc(x) for x in r) + "\n" for r in rows]
    lines.append("\\.\n")
    return "".join(lines)


for old in init_dir.glob("0[2-9]-seed*.sql"):
    old.unlink()

surah_cols = ["id", "name_ar", "name_en", "ayah_count"]
rows = src.execute(f"SELECT {', '.join(surah_cols)} FROM surahs ORDER BY id").fetchall()
(init_dir / "02-seed-surahs.sql").write_text(HEADER + copy_block("surahs", surah_cols, rows), encoding="utf-8")

ayah_cols = ["id", "surah_id", "ayah_number", "text_ar", "text_ar_plain", "page"]
rows = src.execute(f"SELECT {', '.join(ayah_cols)} FROM ayahs ORDER BY id").fetchall()
for i in range(0, len(rows), ROWS_PER_FILE):
    name = f"03-seed-ayahs-{i // ROWS_PER_FILE + 1:02d}.sql"
    (init_dir / name).write_text(HEADER + copy_block("ayahs", ayah_cols, rows[i:i + ROWS_PER_FILE]), encoding="utf-8")
print("wrote seed files to", init_dir)
